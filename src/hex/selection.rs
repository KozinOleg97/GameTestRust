use bevy::prelude::*;

use super::HexCoordinates;

/// Гекс под курсором: предпросмотр, который пересчитывается каждый кадр.
///
/// Предпросмотр живёт в домене, а не в панели: панель только показывает то, что
/// уже решено здесь, и её можно пересоздать или заменить, ничего не сломав.
#[derive(Resource, Debug, Default)]
pub struct HoveredHex(pub Option<HexCoordinates>);

/// Гекс, закреплённый кликом.
///
/// Это устойчивый выбор, к которому будут привязываться действия над объектами:
/// инвентарь, постройки, приказы. Поэтому хранится именно координата — ключ, по
/// которому домен всегда найдёт актуальные данные, а не снимок этих данных.
#[derive(Resource, Debug, Default)]
pub struct SelectedHex(pub Option<HexCoordinates>);
